package storage

import (
	"context"
	"errors"
	"fmt"

	"contgen/internal/storage/dbgen"

	"github.com/jackc/pgx/v5"
)

// RenderPrice is the current course-project price used by the cart UI.
// Actual payment is deliberately kept separate: an order remains CART until
// Telegram Stars (or another configured method) confirms a payment.
const RenderPrice = 50
const MaxCartItems = 10

var (
	ErrNotFound            = errors.New("запись не найдена или недоступна")
	ErrInvalid             = errors.New("некорректные данные")
	ErrEmptyCart           = errors.New("корзина пуста")
	ErrCartFull            = errors.New("в корзине уже 10 видео")
	ErrUnavailableResource = errors.New("данные или музыка недоступны; удалите позицию из корзины")
)

// AddCartItem validates all resource ownership inside one transaction. The
// SQL queries remain generated by sqlc; this method contains only the rule
// that connects them into the cart operation.
func (s *Storage) AddCartItem(ctx context.Context, userID, datasetID int64, musicID *int64, theme dbgen.RenderTheme) (dbgen.RenderJob, error) {
	var zero dbgen.RenderJob
	if userID <= 0 || datasetID <= 0 || !theme.Valid() || (musicID != nil && *musicID <= 0) {
		return zero, ErrInvalid
	}
	tx, err := s.Pool.Begin(ctx)
	if err != nil {
		return zero, err
	}
	defer tx.Rollback(ctx)
	q := s.WithTx(tx)
	if _, err := q.LockUser(ctx, userID); err != nil {
		return zero, unavailable(err)
	}
	if _, err := q.GetDatasetForUser(ctx, dbgen.GetDatasetForUserParams{ID: datasetID, ViewerID: userID}); err != nil {
		return zero, unavailable(err)
	}
	hasPoints, err := q.DatasetHasPoints(ctx, datasetID)
	if err != nil {
		return zero, err
	}
	if !hasPoints {
		return zero, fmt.Errorf("%w: набор данных пуст", ErrInvalid)
	}
	if musicID != nil {
		if _, err := q.GetMusicForUser(ctx, dbgen.GetMusicForUserParams{ID: *musicID, ViewerID: userID}); err != nil {
			return zero, unavailable(err)
		}
	}
	cart, err := q.EnsureCart(ctx, userID)
	if err != nil {
		return zero, err
	}
	count, err := q.CountOrderItems(ctx, cart.ID)
	if err != nil {
		return zero, err
	}
	if count >= MaxCartItems {
		return zero, ErrCartFull
	}
	job, err := q.CreateRenderJob(ctx, dbgen.CreateRenderJobParams{OrderID: cart.ID, DatasetID: datasetID, MusicTrackID: musicID, Theme: theme})
	if err != nil {
		return zero, err
	}
	if err := tx.Commit(ctx); err != nil {
		return zero, err
	}
	return job, nil
}

func (s *Storage) RemoveCartItem(ctx context.Context, userID, jobID int64) error {
	tx, err := s.Pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx)
	q := s.WithTx(tx)
	if _, err := q.LockUser(ctx, userID); err != nil {
		return unavailable(err)
	}
	cart, err := q.GetCartItemOrder(ctx, dbgen.GetCartItemOrderParams{JobID: jobID, UserID: userID})
	if err != nil {
		return unavailable(err)
	}
	n, err := q.DeleteCartItem(ctx, dbgen.DeleteCartItemParams{ID: jobID, OrderID: cart.ID})
	if err != nil {
		return err
	}
	if n == 0 {
		return ErrNotFound
	}
	return tx.Commit(ctx)
}

func (s *Storage) RetryJob(ctx context.Context, userID, jobID int64) error {
	n, err := s.RetryOwnedJob(ctx, dbgen.RetryOwnedJobParams{ID: jobID, UserID: userID})
	if err != nil {
		return err
	}
	if n == 0 {
		return ErrNotFound
	}
	return nil
}

func unavailable(err error) error {
	if errors.Is(err, pgx.ErrNoRows) {
		return ErrNotFound
	}
	return err
}
